export function weekdayFromDate(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number);
  const day = new Date(y, m - 1, d).getDay(); // 0 Sun … 6 Sat
  const map = [
    'sunday',
    'monday',
    'tuesday',
    'wednesday',
    'thursday',
    'friday',
    'saturday',
  ];
  return map[day];
}

export function getDayPlan(weekdayKey) {
  const plan = WEEKLY_PLAN[weekdayKey];
  if (!plan) return null;
  return {
    ...plan,
    exercises: plan.exerciseIds.map((id) => EXERCISES[id]),
  };
}

export function getPlanForDate(dateStr) {
  return getDayPlan(weekdayFromDate(dateStr));
}

export function emptyGymState() {
  return { exercises: {} };
}

/** True when every planned exercise for that weekday is marked done */
export function isGymDayComplete(weekdayKey, gymState) {
  const plan = WEEKLY_PLAN[weekdayKey];
  if (!plan) return false;
  const done = gymState?.exercises || {};
  return plan.exerciseIds.every((id) => !!done[id]);
}
